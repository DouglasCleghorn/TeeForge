``````

[Usage guide](../agent-guide.md) · [All recipes](index.md)
"@
    Add-Generated "docs/recipes/$($recipe.Slug).md" $content
    $recipeLinks.Add("- [$($recipe.Title)]($($recipe.Slug).md): $($recipe.Note)")
}
Add-Generated 'docs/recipes/index.md' ("# TeeForge runnable C# recipes`n`nTeeForge $version · .NET 10 · **$($config.releaseStatus)**`n`n" + ($recipeLinks -join "`n"))
$hashCode = '```csharp' + "`n" + (Read-Source 'samples/TeeForge.Quickstart/HashExample.cs') + "`n" + '```'
$guide = (Read-Source 'docs/agent-guide.template.md').Replace('{{VERSION}}', $version).Replace('{{STATUS}}', $config.releaseStatus).Replace('{{HASH_EXAMPLE}}', $hashCode)
Add-Generated 'docs/agent-guide.md' $guide

$apiLines = @((Read-Source 'src/TeeForge/PublicAPI.Shipped.txt') -split "`n") +
    @((Read-Source 'src/TeeForge/PublicAPI.Unshipped.txt') -split "`n")
$removed = @($apiLines | Where-Object { $_.StartsWith('*REMOVED*') } | ForEach-Object { $_.Substring(9) })
$apiLines = @($apiLines | Where-Object { $_ -and !$_.StartsWith('#') -and !$_.StartsWith('*REMOVED*') -and $_ -notin $removed } | Sort-Object -Unique)
[Array]::Sort($apiLines, [StringComparer]::Ordinal)
$api = "# TeeForge public API reference`n`nVersion $version · **$($config.releaseStatus)** · .NET 10.`n`n" +
    "Generated from the analyzer-checked public API baseline. This is signature notation, not copyable C#: ! marks a non-null reference, ? marks a nullable reference, and -> introduces the return type. Use the [recipes](recipes/index.md) for runnable C# and the [specification](specification.md) for behavior.`n"
foreach ($feature in @('Broadcasting', 'Composition', 'ErasureCoding', 'Hashing', 'Mirroring', 'Networking', 'RandomAccess')) {
    $members = @($apiLines | Where-Object { $_ -match 'TeeForge\.([A-Za-z]+)\.' -and $Matches[1] -eq $feature })
    $api += "`n## TeeForge.$feature`n`n" + '```text' + "`n" + ($members -join "`n") + "`n" + '```' + "`n"
}
Add-Generated 'docs/api-reference.md' $api

# Current-version snapshots are refreshed together. Earlier version folders are left untouched.
$currentDocs = @($generated.Keys)
foreach ($path in $currentDocs) {
    Add-Generated ("docs/versions/$version/" + $path.Substring(5)) $generated[$path]
}
foreach ($name in @('specification.md', 'replica-stream.md', 'erasure-stream.md', 'multipath-stream.md')) {
    $sourceRef = if ($config.releaseStatus -eq 'released') { "v$version" } else { 'main' }
    $contract = (Read-Source "docs/$name").Replace('](benchmarks/README.md', "](https://github.com/DouglasCleghorn/TeeForge/blob/$sourceRef/docs/benchmarks/README.md").Replace('](../samples/', "](https://github.com/DouglasCleghorn/TeeForge/blob/$sourceRef/samples/")
    Add-Generated "docs/versions/$version/$name" $contract
}
Add-Generated "docs/versions/$version/version.json" ([ordered]@{ version = $version; status = $config.releaseStatus; framework = 'net10.0' } | ConvertTo-Json)
