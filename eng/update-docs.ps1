``````

The runner calls this example's RunAsync method with a cancellation token. The
example checks its result and throws on failure. Source: samples/TeeForge.Quickstart/$($recipe.File).

<!-- Generated by eng/update-docs.ps1. Edit the C# source, then regenerate. -->
``````csharp
