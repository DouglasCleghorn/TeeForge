$differences = [Collections.Generic.List[string]]::new()
foreach ($entry in $generated.GetEnumerator()) {
    $destination = Join-Path $repoRoot $entry.Key
    if (!(Test-Path -LiteralPath $destination) -or [IO.File]::ReadAllText($destination).Replace("`r`n", "`n") -cne $entry.Value) {
        if ($Check) { $differences.Add($entry.Key) }
        else {
            [IO.Directory]::CreateDirectory((Split-Path $destination -Parent)) | Out-Null
            [IO.File]::WriteAllText($destination, $entry.Value, $utf8)
        }
    }
}
if ($differences.Count) { throw "Generated documentation is stale. Run ./eng/update-docs.ps1. Files: $($differences -join ', ')" }
Write-Output "Documentation for $version is current ($($generated.Count) generated files)."
